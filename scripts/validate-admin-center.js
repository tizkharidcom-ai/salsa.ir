'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root,p),'utf8');
const admin = read('admin.html');
const js = read('js/admin.js');
const professional = read('js/admin-professional-v4.js');
const css = read('css/admin-command-center-v2.css');
const server = read('server/server.js');
const otpPolicy = read('server/otp-policy.js');
const pg = read('server/postgres-state.js');
const checks=[];
const ok=(name,pass)=>checks.push({name,pass:!!pass});
ok('admin viewport allows zoom', /viewport-fit=cover/.test(admin) && !/user-scalable=no/.test(admin));
ok('admin noindex nofollow', /noindex, nofollow/.test(admin));
ok('admin referrer policy', /name="referrer" content="same-origin"/.test(admin));
ok('admin skip link', /admin-skip-link/.test(admin));
ok('admin nav labelled', /aria-label="ناوبری مرکز فرمان"/.test(admin));
ok('main focusable and busy-aware', /id="main" tabindex="-1" aria-busy="false"/.test(admin));
ok('toast live region', /id="toast" role="status" aria-live="polite"/.test(admin));
ok('sidebar search labelled', /جست‌وجوی بخش‌های مرکز فرمان/.test(professional) && /id="admin-nav-search"/.test(professional));
ok('admin v2 css loaded', /admin-command-center-v2\.css/.test(admin));
ok('tab descriptions exist', /TAB_DESCRIPTIONS/.test(js));
ok('403 does not redirect login', /status === 403/.test(js) && /دسترسی کافی/.test(js));
ok('api request timeout', /AbortController/.test(js) && /20000/.test(js));
ok('api same-origin credentials', /credentials: 'same-origin'/.test(js));
ok('workspace table enhancer', /table-scroll/.test(js) && /scope', 'col'/.test(js));
ok('navigation aria-current', /aria-current/.test(js));
ok('offline user feedback', /اتصال اینترنت قطع است/.test(js));
ok('reduced motion supported', /prefers-reduced-motion/.test(css));
ok('mobile sidebar bounded', /width:min\(88vw,22rem\)/.test(css));
ok('tables horizontally safe', /table-scroll/.test(css));
ok('focus visible rules', /focus-visible/.test(css));
ok('server hides technology header', /disable\('x-powered-by'\)/.test(server));
ok('security headers', /X-Content-Type-Options/.test(server) && /X-Frame-Options/.test(server) && /Permissions-Policy/.test(server));
ok('admin APIs no-store', /Cache-Control', 'no-store'/.test(server));
ok('json body bounded', /express\.json\(\{ limit: '1mb' \}\)/.test(server));
ok('cross-origin writes blocked', /cross_origin_write_blocked/.test(server));
ok('session expiry enforced', /SESSION_TTL_MS/.test(server) && /Date\.now\(\) - Number\(data\.ts\)/.test(server));
ok('secure cookie on https', /secureCookie/.test(server) && /; Secure/.test(server));
ok('OTP request cooldown and retry-after behavior are retained', /const enforceCooldown = !IS_NODE_TEST_RUNTIME/.test(server) && /Retry-After/.test(server));
ok('OTP verification rejects wrong codes and bounds attempts', /entry\.attempts/.test(server) && /entry\.code !== code/.test(server) && /MAX_OTP_ATTEMPTS/.test(server));
ok('production can never disclose a demo OTP, even with the demo flag set', /isOtpDemoMode\(process\.env\)/.test(server) && /nodeEnv === 'production'/.test(otpPolicy) && /return false/.test(otpPolicy) && /503/.test(server));
ok('snapshot writes atomic', /renameSync\(tmpPath, DB_PATH\)/.test(server));
ok('secret file restricted', /chmodSync\(SECRET_PATH, 0o600\)/.test(server));
ok('upload filename server-controlled', /crypto\.randomBytes\(8\)/.test(server));
ok('graceful shutdown', /SIGTERM/.test(server) && /stateStore\.close/.test(server));
ok('postgres pool bounded', /DATABASE_POOL_MAX/.test(pg) && /connectionTimeoutMillis/.test(pg));
const failed=checks.filter(x=>!x.pass);
for(const c of checks) console.log(`${c.pass?'PASS':'FAIL'} ${c.name}`);
console.log(`\n${checks.length-failed.length}/${checks.length} admin hardening checks passed`);
if(failed.length) process.exit(1);
