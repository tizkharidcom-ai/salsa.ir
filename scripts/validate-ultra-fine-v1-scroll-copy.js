'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=r=>fs.readFileSync(path.join(ROOT,r),'utf8');
const v12=read('js/westo-production-v12.js');
const css=read('css/westo-v14.3-ultra-fine.css');
const app=read('js/westo-app.smart.js');
const critical=read('css/westo-critical.smart.css');
const index=read('index.html');
const loader=read('js/westo-smart-loader.js');
let pass=0,fail=0;const failures=[];
const check=(name,ok)=>{if(ok)pass++;else{fail++;failures.push(name)}};
check('old v12 duplicate hint markup removed',!v12.includes('class="westo-v12-hero-hint"')&&!v12.includes('data-v12-hint'));
check('canonical legacy scroll copy is adopted',v12.includes("heroScrollCopy = $('.scroll_discover')")&&v12.includes("heroDesc.insertAdjacentElement('afterend', heroScrollCopy)"));
check('canonical copy gets dedicated class',v12.includes("heroScrollCopy.classList.add('westo-v12-hero-scroll-copy')"));
check('language paint targets canonical copy',v12.includes("if (heroScrollCopy) heroScrollCopy.textContent = lang() === 'en'"));
check('canonical copy is no longer absolute',css.includes('.westo-v12-hero-copy > .scroll_discover.westo-v12-hero-scroll-copy')&&css.includes('position:static !important'));
check('canonical copy shimmer is disabled',css.includes('animation:none !important')&&css.includes('background-image:none !important'));
check('canonical copy remains centered and muted',css.includes('text-align:center !important')&&css.includes('color:var(--prod-muted) !important'));
check('mobile copy remains compact',/@media \(max-width:767px\)[\s\S]*?westo-v12-hero-scroll-copy[\s\S]*?font-size:9px !important/.test(css));
check('smart app contains adopted copy',app.includes("heroDesc.insertAdjacentElement('afterend', heroScrollCopy)")&&!app.includes('data-v12-hint>برای دیدن غذاها اسکرول کنید'));
check('critical bundle contains static copy rule',critical.includes('Ultra Fine v1.1 — canonical hero scroll instruction'));
const release=(loader.match(/const VERSION = '([^']+)'/)||[])[1]||'';
check('Ultra Fine cache generation active',release.startsWith('release14uf1'));
check('index uses new app generation',index.includes(`westo-app.smart.js?v=${release}`));
console.log(JSON.stringify({pass,fail,failures,release},null,2));
if(fail) process.exit(1);
