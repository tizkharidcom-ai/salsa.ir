'use strict';

// Generate the disk-friendly counterpart of /api/content-bootstrap.js.
// It deliberately calls the server's public payload factory so a static copy
// never serializes accounts, orders, sessions, or other private database data.
const fs = require('fs');
const path = require('path');
const { publicContentPayload } = require('../server/server');

const ROOT = path.resolve(__dirname, '..');
const output = path.join(ROOT, 'js', 'content-bootstrap.static.js');
// The hosted public app needs the catalogue even when live inventory is not
// available in the static build environment. Checkout submission still goes
// through the authoritative order validation path.
const payload = publicContentPayload({ includeUnavailable: true });
const json = JSON.stringify(payload)
  .replace(/</g, '\\u003c')
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029');

fs.writeFileSync(
  output,
  `/* Generated by scripts/build-static-content-bootstrap.js. Do not edit. */\nwindow.__WESTO_STATIC_CONTENT__=${json};\n`,
);
console.log(`js/content-bootstrap.static.js\t${Buffer.byteLength(json)} bytes`);
