'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=(r)=>fs.readFileSync(path.join(ROOT,r),'utf8');
const index=read('index.html');
const build=read('scripts/build-smart-bundles.js');
const app=read('js/westo-app.smart.js');
const css=read('css/westo-critical.smart.css');
const promo=read('js/entrance-promo-deck.js');
const admin=read('js/admin.js');
const server=read('server/server.js');
const db=JSON.parse(read('server/data/db.json'));
const loader=read('js/westo-smart-loader.js');
const release=(loader.match(/const VERSION = '([^']+)'/)||[])[1]||'';
let pass=0,fail=0; const failures=[];
const check=(name,ok)=>{ if(ok){pass++;} else {fail++;failures.push(name);} };

check('v14.1 polish bundled',build.includes("'css/westo-v14.1-experience-polish.css'"));
check('entrance promo css bundled',build.includes("'css/entrance-promo-deck.css'"));
check('entrance promo js bundled',build.includes("'js/entrance-promo-deck.js'"));
check('menu promo js removed from bundle',!build.includes("'js/menu-promo-deck.js'"));
check('menu promo css removed from bundle',!build.includes("'css/menu-promo-deck.css'"));
check('app contains one entrance deck',(app.match(/WESTO Entrance Promo Deck v(?:13\.6|14\.3)/g)||[]).length===1);
check('app excludes menu deck',!app.includes('WESTO Menu Promo Deck v13.9'));
check('promo mounts into experience',promo.includes("experience.insertBefore(root, steps)"));
check('promo filters entrance placement',promo.includes("['entrance','both']"));
check('progress still unique',(index.match(/id="eg-progress"/g)||[]).length===1);
check('progress is after enter button',index.indexOf('id="eg-progress"')>index.indexOf('id="eg-enter"'));
check('progress visually integrated',css.includes('Progress is visually contained by the CTA'));
check('mobile footer unified',css.includes('Mobile footer becomes one coherent bottom navigation surface'));
check('mobile footer no blur',/\.eg-foot[\s\S]{0,1000}backdrop-filter:none !important/.test(css));
check('header safe-zone marker',css.includes('Navbar collision-proofing'));
check('header explicit center track',css.includes("grid-template-columns:minmax(0,1fr) clamp(118px,17vw,190px) minmax(0,1fr)"));
check('narrow header icon-only menu',css.includes("@media (max-width:360px)")&&css.includes('.navbar_menu-button .text-block { display:none'));
check('promo no permanent will-change',css.includes('.eg-promo__card { will-change:auto'));
check('promo share blur removed',css.includes('.eg-promo__share { backdrop-filter:none'));
check('short viewport compaction',css.includes('@media (max-width:767px) and (max-height:720px)'));
check('light footer variant',css.includes("html[data-theme='light'] #westo-entrance .eg-foot"));
check('progress light contrast',css.includes("html[data-theme='light'] #westo-entrance .eg-cta-wrap > .eg-progress"));
check('admin default entrance',admin.includes("placement: 'entrance'"));
check('admin placement option entrance',admin.includes("['entrance', 'صفحه ورود — داخل بخش تجربه']"));
check('server default entrance',server.includes("placement: 'entrance', shareEnabled: true"));
check('server fallback entrance',server.includes("current.placement : 'entrance'"));
check('db promos migrated',Array.isArray(db.promoSlides)&&db.promoSlides.every(s=>s.placement==='entrance'));
check('active release css',release&&index.includes(`westo-critical.smart.css?v=${release}`));
check('active release loader',release&&index.includes(`westo-smart-loader.js?v=${release}`));
check('active release app preload',release&&index.includes(`westo-app.smart.js?v=${release}`));
check('server early hints active release',release&&server.includes(`westo-app.smart.js?v=${release}`)&&server.includes(`westo-critical.smart.css?v=${release}`));
check('progress aria retained',/role="progressbar"[^>]*aria-valuemin="0"[^>]*aria-valuemax="100"/.test(index));
check('promo reduced motion retained',css.includes('@media (prefers-reduced-motion:reduce)'));
check('promo keyboard retained',promo.includes("deck.addEventListener('keydown'"));
check('promo pointer drag retained',promo.includes("deck.addEventListener('pointermove'"));
check('promo share isolated',promo.includes("e.target.closest('.eg-promo__share')"));
check('promo scheduler integration',promo.includes('scheduler.bindImage'));
check('promo analytics retained',promo.includes("report(slide.id,'impression')"));
check('promo autoplay remains opt-in',promo.includes('autoplayMs'));
check('footer labels hidden on mobile',css.includes('#westo-entrance .eg-dock__label')&&css.includes('display:none !important'));

console.log(JSON.stringify({pass,fail,failures},null,2));
if(fail) process.exit(1);
